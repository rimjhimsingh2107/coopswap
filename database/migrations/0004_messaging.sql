create table conversations (
  id              uuid primary key default gen_random_uuid(),
  listing_id      uuid not null references listings (id) on delete restrict,
  -- the two user ids, sorted and joined. one conversation per pair per listing
  pair_key        text not null,
  last_seq        bigint not null default 0,
  last_message_at timestamptz,
  created_at      timestamptz not null default now()
);
create unique index conversations_listing_pair_key on conversations (listing_id, pair_key);

create table conversation_participants (
  conversation_id    uuid not null references conversations (id) on delete cascade,
  user_id            uuid not null references users (id) on delete cascade,
  last_read_seq      bigint not null default 0,
  last_delivered_seq bigint not null default 0,
  joined_at          timestamptz not null default now(),
  primary key (conversation_id, user_id),
  constraint participants_read_le_delivered check (last_read_seq <= last_delivered_seq)
);
create index conversation_participants_user_idx on conversation_participants (user_id);

-- seq is assigned by bumping conversations.last_seq inside the insert
-- transaction, so it's gapless and strictly ordered per conversation.
-- client_id is generated by the sender so retries don't double post.
create table messages (
  id              uuid primary key default gen_random_uuid(),
  conversation_id uuid not null references conversations (id) on delete cascade,
  seq             bigint not null,
  sender_id       uuid not null references users (id) on delete restrict,
  body            text not null check (char_length(body) between 1 and 4000),
  client_id       uuid not null,
  created_at      timestamptz not null default now(),
  constraint messages_conversation_seq_key unique (conversation_id, seq),
  constraint messages_client_id_key unique (conversation_id, sender_id, client_id)
);
